const DICTS = { 'pt-BR': pt, en };
let current = 'pt-BR';

export function setLang(lang) { current = DICTS[lang] ? lang : 'en'; document.documentElement.lang = current; }
export const getLang = () => current;
export const otherLang = () => (current === 'pt-BR' ? 'en' : 'pt-BR');

export function t(key, vars = {}) {
  const s = DICTS[current][key] ?? en[key] ?? key;
  return String(s).replace(/\{(\w+)\}/g, (m, k) => (k in vars ? String(vars[k]) : m));
}

/** Language from the browser: Portuguese speakers get pt-BR, everyone else English. */
export function browserLang() {
  return String(navigator.language || '').toLowerCase().startsWith('pt') ? 'pt-BR' : 'en';
}
